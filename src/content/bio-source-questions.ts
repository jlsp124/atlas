import type {
  Assignment,
  CompanionQuestion,
  Concept,
  Edge,
} from '../core/schema';

type Row = [
  prompt: string,
  idea: string,
  asking: string,
  reasoning: string,
  ...include: string[],
];
export function bioQuestion(
  id: string,
  number: string,
  section: string,
  row: Row,
): CompanionQuestion {
  const [prompt, concept, asking, reasoning, ...include] = row;
  return {
    id,
    number,
    section,
    prompt,
    asking,
    concepts: [concept],
    input: 'text',
    clues: [],
    steps: [
      { title: 'Understand the question', text: asking },
      { title: 'Connect the evidence', text: reasoning },
    ],
    hints: [reasoning],
    example: reasoning,
    repair: {
      prompt: 'What should your written answer explain?',
      choices: [
        'The requested idea with supporting facts',
        'An unrelated definition',
      ],
      answer: 'The requested idea with supporting facts',
      explanation: asking,
    },
    checklist: include.length ? include : [asking],
  };
}
const rows = (prefix: string, section: string, items: Row[]) =>
  items.map((row, i) =>
    bioQuestion(`${prefix}-${i + 1}`, String(i + 1), section, row),
  );

